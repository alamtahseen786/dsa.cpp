// BITWISE OPERATOR-calculate krta hai numbers ko binary form me lakr then gives answer
#include<iostream>
using namespace std;

int main(){
// bitwise left shift operator 
cout<<(4<<1)<<endl;

// bitwise right shift operator
cout<<(10>>1)<<endl;

// bitwise and (&) operator
cout<<(4 & 8)<<endl;

// biwise or (|) operator
cout<<(4 | 8)<<endl;

// bitwise exclusive or (XOR,^) operator
cout<<(4 ^ 8)<<endl;
}